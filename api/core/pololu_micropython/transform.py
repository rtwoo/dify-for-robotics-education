def _walk_linear_nodes(
    start_id: str,
    nodes_by_id: dict[str, dict[str, Any]],
    edges: list[dict[str, Any]],
    diagnostics: list[PololuDiagnostic],
) -> list[dict[str, Any]]:
    outgoing: dict[str, list[dict[str, Any]]] = {}
    for edge in edges:
        source = edge.get("source")
        if isinstance(source, str):
            outgoing.setdefault(source, []).append(edge)

    ordered: list[dict[str, Any]] = []
    seen: set[str] = set()
    current_id: str | None = start_id
    while current_id:
        if current_id in seen:
            diagnostics.append(PololuDiagnostic(message="Pololu v1 supports only linear workflows, not graph cycles."))
            break
        seen.add(current_id)
        node = nodes_by_id.get(current_id)
        if node is None:
            diagnostics.append(PololuDiagnostic(message=f"Workflow edge points to missing node: {current_id}"))
            break
        ordered.append(node)
        next_edges = sorted(outgoing.get(current_id, []), key=lambda item: str(item.get("id", "")))
        if len(next_edges) > 1:
            diagnostics.append(
                PololuDiagnostic(message="Pololu v1 supports only one outgoing edge per robot-control node.")
            )
        next_edge = next_edges[0] if next_edges else None
        current_id = str(next_edge.get("target")) if next_edge and next_edge.get("target") else None
    return ordered


def _node_type(node: dict[str, Any]) -> str:
    data = node.get("data")
    if not isinstance(data, dict):
        return ""
    value = data.get("type")
    return str(value) if value is not None else ""


def _statement_from_node_data(
    node_id: str,
    data: dict[str, Any],
    diagnostics: list[PololuDiagnostic],
) -> PololuStatement | None:
    try:
        operation = PololuOperation(str(data.get("operation")))
    except ValueError:
        diagnostics.append(PololuDiagnostic(message="Unsupported Pololu operation.", node_id=node_id))
        return None

    parameters = data.get("parameters")
    if parameters is None:
        parameters = {}
    if not isinstance(parameters, dict):
        diagnostics.append(PololuDiagnostic(message="Pololu operation parameters must be an object.", node_id=node_id))
        return None
    statement_id = data.get("statement_id")
    if not isinstance(statement_id, str) or not statement_id:
        statement_id = _new_statement_id()
    try:
        return PololuStatement(
            statement_id=statement_id,
            node_id=node_id,
            operation=operation,
            parameters=parameters,
        )
    except ValidationError as exc:
        diagnostics.append(PololuDiagnostic(message=str(exc), node_id=node_id))
        return None


def _statement_to_code(statement: PololuStatement) -> list[str]:
    params = statement.parameters
    match statement.operation:
        case PololuOperation.SET_MOTORS:
            return [f"motors.set_speeds({int(params.get('left', 0))}, {int(params.get('right', 0))})"]
        case PololuOperation.STOP_MOTORS:
            return ["motors.off()"]
        case PololuOperation.WAIT:
            return [f"sleep({float(params.get('seconds', 0.0)):g})"]
        case PololuOperation.DISPLAY_TEXT:
            text = json.dumps(str(params.get("text", "")))
            x = int(params.get("x", 0))
            y = int(params.get("y", 0))
            return ["display.fill(0)", f"display.text({text}, {x}, {y})", "display.show()"]
        case PololuOperation.YELLOW_LED:
            method = "on" if bool(params.get("on", True)) else "off"
            return [f"yellow_led.{method}()"]
        case PololuOperation.RGB_LED:
            led = int(params.get("led", 0))
            red = int(params.get("red", 0))
            green = int(params.get("green", 0))
            blue = int(params.get("blue", 0))
            return [f"rgb_leds.set({led}, ({red}, {green}, {blue}))", "rgb_leds.show()"]
        case PololuOperation.BUZZER_BEEP:
            return ["buzzer.beep()"]


def _parse_statement(
    body: list[ast.stmt],
    index: int,
    metadata_by_line: dict[int, _StatementMetadata],
    diagnostics: list[PololuDiagnostic],
) -> tuple[PololuStatement | None, int]:
    stmt = body[index]
    metadata = _nearest_metadata(metadata_by_line, getattr(stmt, "lineno", 0))
    statement_id = metadata.statement_id or _new_statement_id()
    node_id = metadata.node_id

    call = _expr_call(stmt)
    if call is None:
        diagnostics.append(_unsupported_stmt_diagnostic(stmt))
        return None, 1

    if _is_method_call(call, "motors", "set_speeds"):
        args = [_literal(arg) for arg in call.args]
        if len(args) != 2 or not all(isinstance(value, int | float) for value in args):
            diagnostics.append(
                PololuDiagnostic(
                    message="motors.set_speeds requires numeric left and right speeds.",
                    line=stmt.lineno,
                )
            )
            return None, 1
        return (
            PololuStatement(
                statement_id=statement_id,
                node_id=node_id,
                operation=PololuOperation.SET_MOTORS,
                parameters={"left": int(args[0]), "right": int(args[1])},
            ),
            1,
        )
    if _is_method_call(call, "motors", "off"):
        return (
            PololuStatement(statement_id=statement_id, node_id=node_id, operation=PololuOperation.STOP_MOTORS),
            1,
        )
    if _is_name_call(call, "sleep"):
        args = [_literal(arg) for arg in call.args]
        if len(args) != 1 or not isinstance(args[0], int | float):
            diagnostics.append(PololuDiagnostic(message="sleep requires one numeric duration.", line=stmt.lineno))
            return None, 1
        return (
            PololuStatement(
                statement_id=statement_id,
                node_id=node_id,
                operation=PololuOperation.WAIT,
                parameters={"seconds": float(args[0])},
            ),
            1,
        )
    if _is_method_call(call, "yellow_led", "on") or _is_method_call(call, "yellow_led", "off"):
        return (
            PololuStatement(
                statement_id=statement_id,
                node_id=node_id,
                operation=PololuOperation.YELLOW_LED,
                parameters={"on": _is_method_call(call, "yellow_led", "on")},
            ),
            1,
        )
    if _is_method_call(call, "buzzer", "beep"):
        return (
            PololuStatement(statement_id=statement_id, node_id=node_id, operation=PololuOperation.BUZZER_BEEP),
            1,
        )
    display = _parse_display_text(body[index : index + 3], statement_id, node_id)
    if display:
        return display, 3
    rgb = _parse_rgb_led(body[index : index + 2], statement_id, node_id)
    if rgb:
        return rgb, 2

    diagnostics.append(_unsupported_stmt_diagnostic(stmt))
    return None, 1


def _parse_display_text(
    statements: list[ast.stmt],
    statement_id: str,
    node_id: str | None,
) -> PololuStatement | None:
    if len(statements) < 3:
        return None
    fill_call = _expr_call(statements[0])
    text_call = _expr_call(statements[1])
    show_call = _expr_call(statements[2])
    if not (fill_call and text_call and show_call):
        return None
    if not (_is_method_call(fill_call, "display", "fill") and _is_method_call(text_call, "display", "text")):
        return None
    if not _is_method_call(show_call, "display", "show"):
        return None
    args = [_literal(arg) for arg in text_call.args]
    if len(args) < 3 or not isinstance(args[0], str):
        return None
    if not isinstance(args[1], int | float) or not isinstance(args[2], int | float):
        return None
    return PololuStatement(
        statement_id=statement_id,
        node_id=node_id,
        operation=PololuOperation.DISPLAY_TEXT,
        parameters={"text": args[0], "x": int(args[1]), "y": int(args[2])},
    )


def _parse_rgb_led(statements: list[ast.stmt], statement_id: str, node_id: str | None) -> PololuStatement | None:
    if len(statements) < 2:
        return None
    set_call = _expr_call(statements[0])
    show_call = _expr_call(statements[1])
    if not (set_call and show_call):
        return None
    if not (_is_method_call(set_call, "rgb_leds", "set") and _is_method_call(show_call, "rgb_leds", "show")):
        return None
    if len(set_call.args) != 2:
        return None
    led = _literal(set_call.args[0])
    color = _literal(set_call.args[1])
    if (
        not isinstance(led, int)
        or not isinstance(color, tuple)
        or len(color) != 3
        or not all(isinstance(value, int | float) for value in color)
    ):
        return None
    return PololuStatement(
        statement_id=statement_id,
        node_id=node_id,
        operation=PololuOperation.RGB_LED,
        parameters={"led": led, "red": int(color[0]), "green": int(color[1]), "blue": int(color[2])},
    )


def _metadata_comments(code: str) -> dict[int, _StatementMetadata]:
    metadata: dict[int, _StatementMetadata] = {}
    try:
        tokens = tokenize.generate_tokens(io.StringIO(code).readline)
        for token in tokens:
            if token.type != tokenize.COMMENT:
                continue
            text = token.string.strip()
            prefix = "# dify:statement "
            if not text.startswith(prefix):
                continue
            values: dict[str, str] = {}
            for part in text[len(prefix) :].split():
                if "=" not in part:
                    continue
                key, value = part.split("=", 1)
                values[key] = value
            metadata[token.start[0]] = _StatementMetadata(
                statement_id=values.get("id"),
                node_id=values.get("node"),
                operation=values.get("op"),
            )
    except tokenize.TokenError:
        return {}
    return metadata


def _nearest_metadata(metadata_by_line: dict[int, _StatementMetadata], line: int) -> _StatementMetadata:
    candidate_lines = [metadata_line for metadata_line in metadata_by_line if metadata_line < line]
    if not candidate_lines:
        return _StatementMetadata()
    nearest_line = max(candidate_lines)
    if nearest_line != line - 1:
        return _StatementMetadata()
    return metadata_by_line[nearest_line]


def _validate_top_level(module: ast.Module, diagnostics: list[PololuDiagnostic]) -> None:
    for stmt in module.body:
        if isinstance(stmt, ast.ImportFrom):
            if not _allowed_import(stmt):
                diagnostics.append(
                    PololuDiagnostic(message="Unsupported import in Pololu MicroPython program.", line=stmt.lineno)
                )
            continue
        if isinstance(stmt, ast.Assign):
            if not _allowed_device_assignment(stmt):
                diagnostics.append(
                    PololuDiagnostic(message="Unsupported top-level device assignment.", line=stmt.lineno)
                )
            continue
        if isinstance(stmt, ast.Try):
            continue
        if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str):
            continue
        diagnostics.append(PololuDiagnostic(message="Unsupported top-level Python construct.", line=stmt.lineno))


def _allowed_import(stmt: ast.ImportFrom) -> bool:
    if stmt.module == "time":
        return {alias.name for alias in stmt.names} <= {"sleep"}
    if stmt.module == "pololu_3pi_2040_robot":
        return {alias.name for alias in stmt.names} == {"robot"}
    return False


def _allowed_device_assignment(stmt: ast.Assign) -> bool:
    allowed_constructors = {
        "button_b": "ButtonB",
        "motors": "Motors",
        "display": "Display",
        "yellow_led": "YellowLED",
        "rgb_leds": "RGBLEDs",
        "buzzer": "Buzzer",
    }
    if len(stmt.targets) != 1 or not isinstance(stmt.targets[0], ast.Name):
        return False
    target_name = stmt.targets[0].id
    expected_ctor = allowed_constructors.get(target_name)
    if expected_ctor is None or not isinstance(stmt.value, ast.Call):
        return False
    call = stmt.value
    return _is_method_call(call, "robot", expected_ctor) and not call.args and not call.keywords


def _devices_for_program(program: PololuProgram) -> set[str]:
    devices: set[str] = set()
    for statement in program.statements:
        match statement.operation:
            case PololuOperation.SET_MOTORS | PololuOperation.STOP_MOTORS:
                devices.add("motors")
            case PololuOperation.DISPLAY_TEXT:
                devices.add("display")
            case PololuOperation.YELLOW_LED:
                devices.add("yellow_led")
            case PololuOperation.RGB_LED:
                devices.add("rgb_leds")
            case PololuOperation.BUZZER_BEEP:
                devices.add("buzzer")
            case PololuOperation.WAIT:
                continue
    return devices


def _cleanup_lines_for_devices(devices: set[str]) -> list[str]:
    lines: list[str] = []
    if "motors" in devices:
        lines.append("motors.off()")
    if "yellow_led" in devices:
        lines.append("yellow_led.off()")
    if "rgb_leds" in devices:
        lines.append("rgb_leds.off()")
    if "buzzer" in devices:
        lines.append("buzzer.off()")
    return lines


def _validate_finally_cleanup(try_node: ast.Try) -> list[PololuDiagnostic]:
    diagnostics: list[PololuDiagnostic] = []
    allowed_cleanup_calls = {
        ("motors", "off"),
        ("yellow_led", "off"),
        ("rgb_leds", "off"),
        ("buzzer", "off"),
    }
    for stmt in try_node.finalbody:
        if isinstance(stmt, ast.Pass):
            continue
        call = _expr_call(stmt)
        if call is None:
            diagnostics.append(_unsupported_stmt_diagnostic(stmt))
            continue
        if any(_is_method_call(call, device, method) for device, method in allowed_cleanup_calls):
            continue
        diagnostics.append(_unsupported_stmt_diagnostic(stmt))
    return diagnostics


def _metadata_comment(statement: PololuStatement) -> str:
    parts = [f"id={statement.statement_id}", f"op={statement.operation.value}"]
    if statement.node_id:
        parts.insert(1, f"node={statement.node_id}")
    return "# dify:statement " + " ".join(parts)


def _expr_call(stmt: ast.stmt) -> ast.Call | None:
    if not isinstance(stmt, ast.Expr) or not isinstance(stmt.value, ast.Call):
        return None
    return stmt.value


def _is_method_call(call: ast.Call, name: str, method: str) -> bool:
    return (
        isinstance(call.func, ast.Attribute)
        and call.func.attr == method
        and isinstance(call.func.value, ast.Name)
        and call.func.value.id == name
    )


def _is_name_call(call: ast.Call, name: str) -> bool:
    return isinstance(call.func, ast.Name) and call.func.id == name


def _literal(node: ast.AST) -> Any:
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
        value = _literal(node.operand)
        if isinstance(value, int | float):
            return value if isinstance(node.op, ast.UAdd) else -value
    if isinstance(node, ast.Tuple):
        return tuple(_literal(item) for item in node.elts)
    return None


def _is_true_constant(node: ast.AST) -> bool:
    return isinstance(node, ast.Constant) and node.value is True


def _is_button_b_exit(stmt: ast.stmt) -> bool:
    if not isinstance(stmt, ast.If):
        return False
    call = stmt.test
    if not isinstance(call, ast.Call) or not _is_method_call(call, "button_b", "check"):
        return False
    return len(stmt.body) == 1 and isinstance(stmt.body[0], ast.Break)


def _finally_stops_motors(try_node: ast.Try) -> bool:
    return any(
        (call := _expr_call(stmt)) is not None and _is_method_call(call, "motors", "off")
        for stmt in try_node.finalbody
    )


def _unsupported_stmt_diagnostic(stmt: ast.stmt) -> PololuDiagnostic:
    return PololuDiagnostic(
        message="Unsupported Python statement in Pololu round-trip subset.",
        line=getattr(stmt, "lineno", None),
        column=getattr(stmt, "col_offset", None),
    )


