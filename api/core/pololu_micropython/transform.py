"""Deterministic graph, IR, and MicroPython transforms for Pololu workflows.

Only compiler-shaped MicroPython is accepted by ``code_to_ir``. The parser uses
``ast`` for Python structure and ``tokenize`` only for optional Dify metadata
comments, keeping code semantics separate from round-trip identity hints.
"""

from __future__ import annotations

